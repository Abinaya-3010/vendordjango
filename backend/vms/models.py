from django.db import models
class Base(models.Model):
 createdAt=models.DateTimeField(auto_now_add=True)
 updatedAt=models.DateTimeField(auto_now=True)
 class Meta: abstract=True
class Vendor(Base):
 name=models.CharField(max_length=255)
 company=models.CharField(max_length=255)
 email=models.EmailField(unique=True)
 phone=models.CharField(max_length=100,blank=True)
 gst=models.CharField(max_length=100,blank=True)
 pan=models.CharField(max_length=100,blank=True)
 category=models.CharField(max_length=50,default='Other')
 bankName=models.CharField(max_length=255,blank=True)
 accountNumber=models.CharField(max_length=255,blank=True)
 ifsc=models.CharField(max_length=100,blank=True)
 rating=models.FloatField(default=3)
 documentUrl=models.CharField(max_length=500,blank=True)
 status=models.CharField(max_length=30,default='Active')
 address=models.TextField(blank=True)
class RFQ(Base):
 title=models.CharField(max_length=255)
 rfqNumber=models.CharField(max_length=40,unique=True,blank=True)
 description=models.TextField(blank=True)
 items=models.JSONField(default=list)
 deadline=models.DateTimeField()
 vendors=models.ManyToManyField(Vendor,blank=True)
 status=models.CharField(max_length=30,default='Draft')
class Quotation(Base):
 rfq=models.ForeignKey(RFQ,on_delete=models.PROTECT)
 vendor=models.ForeignKey(Vendor,on_delete=models.PROTECT)
 totalPrice=models.FloatField()
 validityDays=models.IntegerField(default=30)
 terms=models.TextField(blank=True)
 deliveryDays=models.IntegerField(null=True,blank=True)
 items=models.JSONField(default=list)
 status=models.CharField(max_length=30,default='Submitted')
 isLowest=models.BooleanField(default=False)
class PurchaseOrder(Base):
 poNumber=models.CharField(max_length=40,unique=True,blank=True)
 rfq=models.ForeignKey(RFQ,on_delete=models.SET_NULL,null=True,blank=True)
 quotation=models.ForeignKey(Quotation,on_delete=models.SET_NULL,null=True,blank=True)
 vendor=models.ForeignKey(Vendor,on_delete=models.PROTECT)
 items=models.JSONField(default=list)
 totalAmount=models.FloatField()
 status=models.CharField(max_length=30,default='Pending')
 deliveryDate=models.DateTimeField(null=True,blank=True)
 notes=models.TextField(blank=True)
class Invoice(Base):
 invoiceNumber=models.CharField(max_length=40,unique=True,blank=True)
 purchaseOrder=models.ForeignKey(PurchaseOrder,on_delete=models.PROTECT)
 vendor=models.ForeignKey(Vendor,on_delete=models.PROTECT)
 items=models.JSONField(default=list)
 subTotal=models.FloatField()
 gstRate=models.FloatField(default=18)
 gstAmount=models.FloatField(default=0)
 totalAmount=models.FloatField(default=0)
 status=models.CharField(max_length=30,default='Pending')
 dueDate=models.DateTimeField(null=True,blank=True)
 paidDate=models.DateTimeField(null=True,blank=True)
class Inventory(Base):
 purchaseOrder=models.ForeignKey(PurchaseOrder,on_delete=models.PROTECT)
 vendor=models.ForeignKey(Vendor,on_delete=models.PROTECT)
 items=models.JSONField(default=list)
 receivedDate=models.DateTimeField(auto_now_add=True)
 notes=models.TextField(blank=True)
